#!/usr/bin/env python3
# breadth_v1 licence-at-source + split-lineage fetch: every upstream repo named by tasksource-jev sources.yaml (pinned revisions), tokenless, paced.
import os, re, json, time, hashlib, sys, yaml, urllib.request, urllib.parse, urllib.error
from huggingface_hub import HfApi, hf_hub_download
D = "/data/local/breadth_v1"; OUT = D + "/lic"; os.makedirs(OUT + "/text", exist_ok=True)
api = HfApi(token=False)
src = yaml.safe_load(open(D + "/meta/ts_jev/sources.yaml"))
repos = {}
for name, v in src["sources"].items():
    for r, sha in (v.get("revisions") or {}).items(): repos.setdefault(r, sha)
    for r in (v.get("originals") or []) + (v.get("data_files_from") or []): repos.setdefault(r, None)
extra = sys.argv[1] if len(sys.argv) > 1 else None
if extra:
    for l in open(extra):
        r = l.strip()
        if r: repos.setdefault(r, None)
done = set()
outp = OUT + "/upstream.jsonl"
if os.path.exists(outp):
    for l in open(outp): done.add(json.loads(l)["repo"])
def slug(s): return re.sub(r"[^A-Za-z0-9._-]+", "__", s)
def get(url, tries=5):
    for a in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "breadth-v1-licence-check"}), timeout=40) as r: return r.status, r.read()
        except urllib.error.HTTPError as e:
            if e.code == 429: time.sleep(30 * (a + 1)); continue
            return e.code, e.read()[:500]
        except Exception as e:
            time.sleep(5 * (a + 1))
    return 0, b""
def retry(fn, tries=5):
    for a in range(tries):
        try: return fn()
        except Exception as e:
            s = repr(e)
            if "429" in s or "Too Many" in s or "timed out" in s or "Connection" in s: time.sleep(30 * (a + 1)); continue
            return ("ERR", s[:300])
    return ("ERR", "retries")
KW = ["gpt-3", "gpt-4", "gpt4", "chatgpt", "openai", "claude", "gemini", "synthetic", "generated by", "llm-generated", "machine-generated", "non-commercial", "noncommercial", "research purposes", "research only", "academic use", "terms of use", "terms of service", "no license", "all rights reserved"]
fo = open(outp, "a")
n = 0
for repo, sha in repos.items():
    if repo in done: continue
    n += 1
    rec = {"repo": repo, "pinned": sha}
    info = retry(lambda: api.dataset_info(repo, revision=sha, files_metadata=False))
    time.sleep(0.35)
    if isinstance(info, tuple):
        rec["error"] = info[1]; fo.write(json.dumps(rec) + "\n"); fo.flush(); print(n, repo, "ERR", info[1][:120], flush=True); continue
    rec["sha"] = info.sha; rec["gated"] = info.gated; rec["private"] = info.private; rec["last_modified"] = str(info.last_modified)
    cd = info.card_data.to_dict() if info.card_data else {}
    rec["card_license"] = cd.get("license"); rec["card_license_name"] = cd.get("license_name"); rec["card_license_link"] = cd.get("license_link")
    rec["card_source_datasets"] = cd.get("source_datasets"); rec["card_task_categories"] = cd.get("task_categories"); rec["card_language"] = cd.get("language") if not isinstance(cd.get("language"), list) or len(cd.get("language")) < 12 else "many"
    files = [s.rfilename for s in info.siblings]
    rec["n_files"] = len(files); rec["has_script"] = any(f.endswith(".py") for f in files)
    low = [f.lower() for f in files]
    rec["file_split_hints"] = sorted({k for k in ("train", "validation", "valid", "dev", "test") for f in low if re.search(r"(^|[/_.\-])" + k + r"([/_.\-]|$)", f)})
    parts = ["CARD_LICENSE: %s | name=%s | link=%s" % (rec["card_license"], rec["card_license_name"], rec["card_license_link"])]
    readme = ""
    if "README.md" in files:
        p = retry(lambda: hf_hub_download(repo, "README.md", repo_type="dataset", revision=info.sha, token=False, cache_dir=D + "/hfcache"))
        time.sleep(0.2)
        if not isinstance(p, tuple): readme = open(p, errors="replace").read()
    rec["readme_chars"] = len(readme)
    lines = readme.split("\n"); keep = set()
    for i, l in enumerate(lines):
        if re.search(r"licen[sc]|copyright|terms of (use|service)|non-?commercial|research purposes|permission", l, re.I):
            for j in range(max(0, i - 1), min(len(lines), i + 4)): keep.add(j)
    parts.append("README_LICENCE_PASSAGES:\n" + "\n".join(lines[j] for j in sorted(keep)))
    lic_files = [f for f in files if re.match(r"(.*/)?(licen[sc]e|copying|notice|terms)[^/]*$", f, re.I) and f.count("/") <= 1][:3]
    rec["licence_files"] = lic_files
    for f in lic_files:
        p = retry(lambda: hf_hub_download(repo, f, repo_type="dataset", revision=info.sha, token=False, cache_dir=D + "/hfcache"))
        time.sleep(0.2)
        if not isinstance(p, tuple) and os.path.getsize(p) < 300000: parts.append("FILE %s:\n%s" % (f, open(p, errors="replace").read()))
    text = "\n\n".join(parts)
    open(OUT + "/text/" + slug(repo) + ".txt", "w").write(text)
    rec["licence_text_sha256"] = hashlib.sha256(text.encode()).hexdigest(); rec["licence_text_chars"] = len(text)
    rl = readme.lower(); rec["kw"] = [k for k in KW if k in rl]
    st, body = get("https://datasets-server.huggingface.co/splits?dataset=" + urllib.parse.quote(repo, safe=""))
    time.sleep(0.35)
    if st == 200:
        try: rec["splits"] = sorted({(s["config"], s["split"]) for s in json.loads(body)["splits"]})
        except Exception as e: rec["splits_error"] = repr(e)[:100]
    else: rec["splits_error"] = "%s %s" % (st, body[:160].decode(errors="replace"))
    fo.write(json.dumps(rec) + "\n"); fo.flush()
    if n % 25 == 0: print(n, repo, rec.get("card_license"), flush=True)
for commit in (src.get("tasksource_commit"),):
    for path in ("src/tasksource/tasks.py", "src/tasksource/mtasks.py"):
        st, body = get("https://raw.githubusercontent.com/sileod/tasksource/%s/%s" % (commit, path))
        print("tasks.py", path, st, len(body), flush=True)
        if st == 200: open(OUT + "/" + os.path.basename(path), "wb").write(body)
print("LIC_DONE", n, flush=True)
