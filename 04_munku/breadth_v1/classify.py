#!/usr/bin/env python3
"""breadth_v1 decisions: joins tasksource-jev sources.yaml (@8df2e5c9) + licence / split facts fetched from each upstream HF repo
(lic.py -> upstream.jsonl, licence text hashed) + the lineage registry (source_lineage_2026-10-26_v1) + the name block list
(DI suite datasets and parents, our held-out / proxy sets, typed-decision imitations). Default deny.

  python3 classify.py META.json UPSTREAM.jsonl TS_SPLITS.json OUTDIR
Writes OUTDIR/decisions.json, licence_lineage.tsv, rejected.tsv, classify_summary.json."""
import collections, json, math, re, sys
META, UP, TSS, OUT = sys.argv[1:5]
d = json.load(open(META)); S = d["y"]["sources"]; REG = d["reg"]["sources"]; ST = d["stats"]
U = {}
for l in open(UP):
    r = json.loads(l); U[r["repo"]] = r

# ---- name block list (default deny). (pattern on the tasksource source name, reason)
BLOCK = [
 (r"^(ai2_arc|anli|banking77|clinc_oos|contract-nli|cnli|esci|hellaswag|hover|humicroedit|isarcasm|winogrande|semeval2014-absa|nli4ct_semeval2024|ragtruth|schema-guided)(/|$)", "DI suite dataset (public eval source)"),
 (r"^hotpotqa(/|$)", "parent of a DI dataset (HoVer is built on HotpotQA)"),
 (r"^winodict(/|$)", "derived from a DI dataset (WinoDict rewrites Winograd / WinoGrande items)"),
 (r"^(IntentGrasp)(/|$)", "aggregate intent benchmark: may contain BANKING77 / CLINC150 (doubt -> deny)"),
 (r"^multilingual/multilingual-NLI-26lang-2mil7", "contains machine-translated ANLI (DI dataset)"),
 (r"^(scifact_entailment)(/|$)", "our own monitor set"),
 (r"^(civil_comments|toxic_conversations|MedQA-USMLE-4-options-hf|folio|HelpSteer2|dices|multipref)(/|$)", "GDE-1 proxy panel dataset (keeps the unseen-domain proxy unseen)"),
 (r"^lex_glue/(ecthr|scotus)", "GDE-1 proxy panel dataset (ECtHR / SCDB)"),
 (r"swiss_judgment", "GDE-1 proxy panel dataset (Swiss judgments)"),
 (r"^(code_x_glue_cc_defect_detection|SChem_Disagreement)(/|$)", "risk list (review 10-26)"),
 (r"^(lewidi|chaos-mnli-ambiguity|help-nli|agent_action_safety|doc-nli|goal-step-wikihow)(/|$)", "withheld in earlier builds (lineage / label doubt)"),
 (r"^(procedural-typed-decisions|synthetic-retrieval-NLI|tasksource_dpo_pairs|privacy-200k-Mistral-Large-3|synthetic-instruct-gptj-pairwise)(/|$)", "synthetic typed-decision style data (outside the zero-shot definition)"),
 (r"^(UltraFeedback-paired|hh-rlhf|WANLI|TuringBench|toxigen-data|oasst2|oasst2_pairwise_rlhf_reward|chatbot_arena_conversations|webinstruct)(/|$)", "text generated by closed / third-party models (terms doubt; recoverable on review)"),
 (r"^(prm800k_dpo)(/|$)", "contains MATH test problems"),
 (r"^(wildguardmix-cleaned)(/|$)", "gated upstream"),
 (r"^(shell-safety-v2|ShellRisk-Bench)(/|$)", "LLM-written safety benchmark rows"),
]
PERM = re.compile(r"^(apache-2\.0|mit|cc-by-[0-9.]+|cc-by-sa-[0-9.]+|cc-by-sa|cc-by|cc0-1\.0|cc0|bsd.*|cdla-.*|odc-by|pddl|unlicense|afl-3\.0|odbl|openrail)$")
def tags(x):
    if x is None: return []
    if isinstance(x, str): x = [x]
    return [str(t).lower().strip() for t in x if t]
def lic_class(tg):
    """restricted > permissive > copyleft > none, over a set of tags from ONE card (dual licences: any permissive option counts)."""
    if any("-nc" in t or "-nd" in t or "noncommercial" in t for t in tg): return "restricted"
    if any(PERM.match(t) for t in tg): return "permissive"
    if any(re.match(r"^(a?gpl|lgpl|gfdl|mpl)", t) for t in tg): return "copyleft"
    return "none"
NCKW = {"non-commercial", "noncommercial", "research purposes", "research only", "academic use", "all rights reserved"}
LLM_REVIEWED_OK = {"codah/codah": "human-written (2019); card names GPT-1 as the adversary model", "PARARULE-Plus": "rule-generated text; card mentions evaluation only",
                   "mindgames": "template-generated epistemic logic; card mentions model evaluation only"}
LLMKW = {"gpt-3", "gpt-4", "gpt4", "chatgpt", "openai", "claude", "gemini", "llm-generated"}
HELD = {"validation", "test", "dev", "valid", "val", "eval"}
tss = json.load(open(TSS)); OVERRIDE_BAD = set()
for name, dn, sp in tss:
    first = json.loads(sp.replace("'", '"').replace("None", "null"))[0]
    if not str(first).startswith("train"):
        OVERRIDE_BAD.add(re.sub(r"_+", "_", name.lower()))
def family(n):
    p = n.split("/")
    return "/".join(p[:2]) if p[0] == "multilingual" and len(p) > 1 else p[0]
def repos(v):
    r = list((v.get("revisions") or {}).keys())
    for k in ("dataset",):
        if v.get(k) and v[k] not in r: r.append(v[k])
    return r

rows = []
for n, v in sorted(S.items()):
    rp = repos(v); orig = list(v.get("originals") or [])
    rec = {"source": n, "family": family(n), "ts_license": v.get("license"), "ts_license_use": v.get("license_use"), "ts_train_rows": (v.get("rows") or {}).get("train"),
           "config": v.get("config"), "upstream": rp, "originals": orig, "revisions": v.get("revisions") or {}, "source_urls": v.get("source_urls") or []}
    cand_c = (ST.get("clean|" + n) or {}).get("cand", 0); cand_n = (ST.get("nc|" + n) or {}).get("cand", 0)
    rec["cand_clean"], rec["cand_nc"] = cand_c, cand_n
    # licence facts read at the source
    ev = []; cls = []; nckw = set(); llmkw = set(); gated = False; hashes = []
    for r in rp + orig:
        u = U.get(r)
        if not u: ev.append(f"{r}: not fetched"); continue
        tg = tags(u.get("card_license")); c = lic_class(tg); cls.append((r, c, tg))
        gated |= bool(u.get("gated")); kw = set(u.get("kw") or [])
        nckw |= {f"{r}:{k}" for k in kw & NCKW}; llmkw |= {f"{r}:{k}" for k in kw & LLMKW}
        if u.get("licence_text_sha256"): hashes.append(f"{r}@{(u.get('sha') or '')[:10]}:{u['licence_text_sha256'][:16]}")
    rec["card_licences"] = [f"{r}={'+'.join(tg) or 'none'}" for r, c, tg in cls]; rec["licence_text_sha256"] = hashes
    if n in LLM_REVIEWED_OK: rec["review_note"] = LLM_REVIEWED_OK[n]; llmkw = set()
    rec["gated"] = gated; rec["kw_nc"] = sorted(nckw); rec["kw_llm"] = sorted(llmkw)
    kinds = [c for _, c, _ in cls]
    # lineage: registry first, else derived from upstream split names (+ tasksource split overrides)
    reg = REG.get("tasksource:" + n)
    if reg:
        rec["split_class"] = reg.get("upstream_split_original"); rec["split_evidence"] = "registry source_lineage_2026-10-26_v1"
    else:
        prim = U.get(rp[0]) if rp else None; names = set()
        if prim and prim.get("splits"):
            cfg = v.get("config"); sp = [s for c, s in prim["splits"] if cfg is None or c == cfg] or [s for c, s in prim["splits"]]
            names = set(sp); src = "HF split names now"
        elif prim:
            names = set(prim.get("file_split_hints") or []); src = "file names (no viewer)"
        else:
            src = "no upstream repo record"
        key = re.sub(r"_+", "_", re.sub(r"[^a-z0-9]+", "_", n.lower()))
        if key in OVERRIDE_BAD or n.split("/")[0].lower() in OVERRIDE_BAD:
            rec["split_class"] = "tasksource_maps_non_train_split"
        elif any("train" in s for s in names) and (names & HELD or any(re.search(r"test|val|dev", s) for s in names)):
            rec["split_class"] = "train"
        elif names and all("train" in s for s in names):
            rec["split_class"] = "train_single_split_upload"
        elif names:
            rec["split_class"] = "no_train_split_upstream"
        else:
            rec["split_class"] = "unknown"
        rec["split_evidence"] = f"derived: {src}: {','.join(sorted(names))[:80]}"
    # ---- decision (first failing rule wins)
    why = None; line = None; tier = None
    for pat, reason in BLOCK:
        if re.search(pat, n): why = "lineage: " + reason; break
    if not why:
        use = v.get("license_use")
        if use == "unspecified": why = "licence: none stated at the source (tasksource: unspecified); recoverable by manual source review"
        elif gated: why = "gated upstream (tokenless only)"
        elif use == "commercial":
            if not cand_c: why = "not in tasksource filtered-full (tasksource's own benchmark-source / protected-text / review holdout) or no base rows"
            elif "restricted" in kinds: why = "licence conflict: a source card carries NC / ND terms: " + ";".join(f"{r}={'+'.join(tg)}" for r, c, tg in cls if c == "restricted")
            elif nckw: why = "licence doubt: source card text mentions " + ",".join(sorted(nckw))
            elif "permissive" in kinds: line = "clean"
            elif "copyleft" in kinds: why = "licence: GPL-family only at the source"
            else: why = "licence: no licence on the source card (tasksource label rests on DPI / other evidence); recoverable by manual review"
            if line and llmkw: line = None; why = "card mentions closed-model generated text: " + ",".join(sorted(llmkw)) + " (review)"
        elif use == "non-commercial":
            tg_all = [t for _, _, tg in cls for t in tg] + tags(re.split(r",\s*", v.get("license") or ""))
            if not cand_n: why = "NC: no base rows"
            elif any("-nd" in t for t in tg_all): why = "licence: no-derivatives terms"
            elif any(re.match(r"^cc-by-nc(-sa)?-[0-9.]+$", t) for t in tg_all): line = "nc"
            else: why = "licence: non-commercial but not a CC BY-NC(-SA) licence (custom / research-only terms)"
            if line and llmkw: line = None; why = "card mentions closed-model generated text: " + ",".join(sorted(llmkw)) + " (review)"
        else: why = f"licence_use {use}"
    if line:
        sc = rec["split_class"]
        if sc in ("train", "own_train_split"): tier = "A"
        elif sc in ("full_eval_set", "mixed_train_dev_test", "mixed_train_eval", "mixed_incl_benchmark_labeled_set", "unknown_likely_eval_suite", "tasksource_maps_non_train_split", "no_train_split_upstream", "validation_part"):
            why = f"lineage: upstream split class {sc} (lineage_gate deny)"; line = None
        else:
            tier = "B"; rec["hold_note"] = f"lineage hold: split class {sc}: usable only with an explicit, disclosed allow-list (built in <line>_tierB, not in the default pool)"
    rec["line"], rec["tier"], rec["reject_reason"] = line, tier, why
    rows.append(rec)

# quotas: per source min(400, max(60, 1600 // n sources of the family that survive))
fam = collections.Counter(r["family"] for r in rows if r["line"])
dec = {}
for r in rows:
    if r["line"]:
        r["quota"] = min(400, max(60, 1600 // fam[r["family"]]))
        r["built_as"] = r["line"] + ("_tierB" if r["tier"] == "B" else "")
        dec[r["source"]] = {"line": r["built_as"], "cand_line": r["line"], "tier": r["tier"], "family": r["family"], "quota": r["quota"]}
json.dump({"sources": dec}, open(f"{OUT}/decisions.json", "w"), indent=0)
H = ["source", "family", "line", "tier", "built_as", "quota", "upstream", "revisions", "originals", "config", "ts_license", "ts_license_use", "card_licences", "licence_text_sha256", "split_class", "split_evidence", "ts_train_rows", "cand_clean", "cand_nc", "kw_llm", "review_note", "hold_note", "reject_reason"]
def cell(x): return json.dumps(x, ensure_ascii=False) if isinstance(x, (list, dict)) else ("" if x is None else str(x))
with open(f"{OUT}/licence_lineage.tsv", "w") as f:
    f.write("\t".join(H) + "\n")
    for r in rows:
        f.write("\t".join(cell(r.get(h)) for h in H) + "\n")
with open(f"{OUT}/rejected.tsv", "w") as f:
    f.write("candidate\twave\treason\n")
    for r in rows:
        if not r["line"]: f.write(f"{r['source']}\ttasksource-jev\t{r['reject_reason']}\n")
summ = {"candidates": len(rows), "survivors": collections.Counter(r["built_as"] for r in rows if r["line"]), "families": {l: len({r["family"] for r in rows if r.get("built_as") == l}) for l in ("clean", "nc", "clean_tierB", "nc_tierB")},
        "quota_rows": {l: sum(r["quota"] for r in rows if r.get("built_as") == l) for l in ("clean", "nc", "clean_tierB", "nc_tierB")},
        "rejected": collections.Counter(re.sub(r":.*", "", r["reject_reason"]) if r["reject_reason"].startswith(("lineage:", "licence conflict", "licence doubt", "card mentions")) and False else r["reject_reason"].split(": a source")[0].split(" mentions")[0].split(" (GDE")[0][:90] for r in rows if not r["line"]).most_common()}
json.dump(summ, open(f"{OUT}/classify_summary.json", "w"), indent=1, default=str)
print(json.dumps(summ, indent=1, default=str))
