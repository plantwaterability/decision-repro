def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", help="output directory (train/, val/, manifest.json)")
    ap.add_argument("--cases-per-schema", type=int, default=130,
                    help="unique cases per schema (default 130: ~20k cases over ~150 schemas)")
    ap.add_argument("--target-cases", type=int, default=None,
                    help="alternative sizing: total cases wanted; sets --cases-per-schema = ceil(target / n_schemas)")
    ap.add_argument("--seed", default="0", help="any string; all randomness derives from it")
    ap.add_argument("--workflows", default="all", help="comma list, default all registered")
    ap.add_argument("--dev-workflows", default=None,
                    help=f"comma list sent ENTIRELY to val (default: {','.join(DEFAULT_DEV)} when selected; '' = none)")
    ap.add_argument("--val-pct", type=int, default=0,
                    help="also hold out this %% of NON-dev cases as in-workflow val (default 0: val = dev workflows)")
    ap.add_argument("--exclude-states", default=None, help="eval jsonl file/dir: run the n-gram overlap audit")
    ap.add_argument("--allow-question-overlap", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--self-test-cases", type=int, default=4, help="cases per schema in the self-test")
    ap.add_argument("--list", action="store_true", help="list workflows, schemas and questions")
    ap.add_argument("--preview", metavar="WORKFLOW", help="print cases for every schema x surface")
    ap.add_argument("--schema", default=None, help="with --preview: one schema only")
    ap.add_argument("--n", type=int, default=1, help="with --preview: cases per surface")
    ap.add_argument("--label-audit", metavar="DIR", help="spread + factor-MI audit of a LABELLED corpus")
    a = ap.parse_args()
    try:
        a.seed = int(a.seed)
    except ValueError:
        pass
    if a.self_test:
        return self_test(a)
    if a.list:
        list_workflows()
        return 0
    if a.preview:
        preview(a)
        return 0
    if a.label_audit:
        label_audit(a.label_audit)
        return 0
    if not a.out:
        ap.error("--out is required to build")
    build(a)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
