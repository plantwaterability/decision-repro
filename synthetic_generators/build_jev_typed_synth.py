#!/usr/bin/env python3
"""
build_jev_typed_synth.py -- backlog item (48): UNLABELLED typed-style synthetic cases over NEW workflows.

Each case comes from a latent-factor schema in synth_workflows/ (one state + five typed questions, the
LocalLLaMA/typed-decisions format). This script writes them as corpus records with no labels; the labeller
(trainers/claude_verbal_label.py) fills `labels` / `label_kind` from open ~4B teachers that verbalise
distributions, K samples averaged, after which trainers/cache_features.iter_units loads them unchanged.
The record contract is research/typed_synth_spec.md section 5 (executable form: synth_workflows/contract.py).

Output:
  <out>/train/typed_synth__<workflow>.jsonl   flat, one file per workflow (iter_units reads one level)
  <out>/val/typed_synth__<workflow>.jsonl     the --dev-workflows go ENTIRELY here (the typed-style dev replica)
  <out>/manifest.json                         counts, type mix, K histogram, surfaces, audits, arguments

Integrity: nothing here reads typed-decisions TRAIN. --exclude-states PATH (a jsonl file or directory of eval
records, e.g. jev_real/test on a node) runs the n-gram overlap audit: generated states that copy an eval state
are dropped, and any question / criterion text that shares a 6-word run with an eval question text stops the build.

  python3 build_jev_typed_synth.py --out /data/local/jev_typed_synth --cases-per-schema 130 --seed 0 \\
      --exclude-states /data/local/jev_real/test
  python3 build_jev_typed_synth.py --list
  python3 build_jev_typed_synth.py --preview it_change_approval --n 2
  PYTHONPATH=/tmp/stubs python3 build_jev_typed_synth.py --self-test          # stubs: torch.py, transformers.py
  python3 build_jev_typed_synth.py --label-audit /path/to/labelled_corpus      # after labelling: spread + factor MI
"""
