def sha(s: str) -> str:
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:16]


def norm(s: str) -> str:
    """Whitespace/case normalisation for exact-duplicate detection (as analysis/claude_overlap.norm)."""
    return re.sub(r"\s+", " ", str(s)).strip().lower()


def file_stem(workflow: str) -> str:
    return f"{SOURCE_PREFIX}__{workflow}"


# =========================================================================== building
def resolve_dev(selected, dev_arg):
    if dev_arg is None:
        dev = [w for w in DEFAULT_DEV if w in selected]
        if not dev:
            print(f"note: none of the default dev workflows {list(DEFAULT_DEV)} is selected; val/ will be empty "
                  f"unless --val-pct > 0")
        return dev
    dev = [w.strip() for w in dev_arg.split(",") if w.strip()]
    bad = [w for w in dev if w not in selected]
    if bad:
        raise SystemExit(f"--dev-workflows {bad} are not among the selected workflows {sorted(selected)}")
    return dev


def make_record(wf, schema, case, seed, index, split, reason):
    qs = case["questions"]
    sig = json.dumps({q: base.option_keys(v) for q, v in qs.items()}, sort_keys=True)
    rid = f"{SOURCE_PREFIX}-{sha(wf.name + '|' + schema.name + '|' + case['state'] + '|' + sig)}"
    return {
        "id": rid, "base_id": rid, "source": f"{SOURCE_PREFIX}/{wf.name}", "license": LICENSE,
        "split": split, "unlabelled": True, "state": case["state"], "questions": qs,
        "meta": {
            "generator": SOURCE_PREFIX, "generator_version": base.GENERATOR_VERSION,
            "workflow": wf.name, "domain": wf.domain, "schema": schema.name,
            "schema_description": schema.description, "surface": case["surface"], "factors": case["factors"],
            "seed": seed, "case_index": index, "split": split, "split_reason": reason,
            "dev_workflow": reason == "dev_workflow", "question_order": list(qs),
            "question_types": {q: v["type"] for q, v in qs.items()}, "n_questions": len(qs),
        },
    }


def build_records(workflows: dict, cases_per_schema: int, seed, dev=(), val_pct: int = 0, max_tries: int = 4):
    """Deterministic under `seed`: (records, stats). Exact-duplicate states (normalised) are skipped and
    re-drawn with the next case index, up to max_tries * N draws per schema."""
    records, seen = [], set()
    stats = {"dedupe_skipped": Counter(), "short_schemas": {}}
    for wname in sorted(workflows):
        wf = workflows[wname]
        for schema in wf.schemas:
            got, i = 0, 0
            while got < cases_per_schema and i < max_tries * cases_per_schema:
                case = base.make_case(schema, base.case_rng(seed, wf.name, schema.name, i))
                key = norm(case["state"])
                if key in seen:
                    stats["dedupe_skipped"][f"{wf.name}/{schema.name}"] += 1
                    i += 1
                    continue
                seen.add(key)
                if wf.name in dev:
                    split, reason = "val", "dev_workflow"
                else:
                    in_val = val_pct and int(sha(f"{seed}|{wf.name}|{schema.name}|{i}"), 16) % 100 < val_pct
                    split, reason = ("val", "in_workflow_val") if in_val else ("train", "train")
                records.append(make_record(wf, schema, case, seed, i, split, reason))
                got += 1
                i += 1
            if got < cases_per_schema:
                stats["short_schemas"][f"{wf.name}/{schema.name}"] = got
    ids = [r["id"] for r in records]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate record ids (state + questions collided); this should be impossible after dedupe")
    stats["dedupe_skipped"] = dict(stats["dedupe_skipped"])
    return records, stats


def summarise(records) -> dict:
    qtype, khist, surf, noul_def = Counter(), Counter(), Counter(), Counter()
    per = defaultdict(Counter)
    lens = sorted(len(r["state"]) for r in records)
    for r in records:
        m = r["meta"]
        per[m["workflow"]][f"{m['schema']}/{r['split']}"] += 1
        surf[m["surface"] if m["surface"] in ("json",) else "text/other"] += 1
        for q in r["questions"].values():
            qtype[q["type"]] += 1
            khist[f"{q['type']}:{len(base.option_keys(q))}"] += 1
            if q["type"] == "noul":
                noul_def["with_definitions" if "criteria" in q else "without"] += 1
    nq = sum(qtype.values()) or 1

    def pctl(p):
        return lens[min(len(lens) - 1, int(p * len(lens)))] if lens else 0
    return {
        "records": len(records), "units": nq,
        "by_split": dict(Counter(r["split"] for r in records)),
        "by_workflow": {w: dict(c) for w, c in sorted(per.items())},
        "qtype_mix": {t: round(qtype[t] / nq, 3) for t in base.QTYPES},
        "k_hist": dict(sorted(khist.items())), "noul_definitions": dict(noul_def),
        "surface_json_share": round(surf["json"] / max(1, len(records)), 3),
        "surfaces": dict(Counter(r["meta"]["surface"] for r in records).most_common()),
        "state_chars": {"min": lens[0] if lens else 0, "p10": pctl(0.1), "p50": pctl(0.5), "p90": pctl(0.9),
                        "max": lens[-1] if lens else 0},
    }


def write_corpus(out: Path, records) -> dict:
    by = defaultdict(list)
    for r in records:
        by[(r["split"], r["meta"]["workflow"])].append(r)
    written = {}
    for split in ("train", "val"):
        (out / split).mkdir(parents=True, exist_ok=True)
    for (split, wname), rs in sorted(by.items()):
        p = out / split / f"{file_stem(wname)}.jsonl"
        with p.open("w", encoding="utf-8") as f:
            for r in rs:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        written[str(p.relative_to(out))] = len(rs)
    return written


def run_audits(records, workflows, path, allow_question_overlap=False):
    eval_states, eval_q = exclusion.read_eval(path)
    st = exclusion.audit_states(records, eval_states)
    qa = exclusion.audit_question_texts(workflows.values(), eval_q)
    print(f"audit vs {path}: {len(eval_states)} eval states, {len(eval_q)} eval question texts")
    print(f"  states: {st['n_flagged']} of {st['n_checked']} flagged ({st['rule']}); "
          f"{st['n_with_any_13gram']} share any 13-gram; worst {st['worst'][:3]}")
    print(f"  question texts: {qa['n_hits']} hits ({qa['rule']})")
    for h in qa["hits"][:20]:
        print(f"    {h['workflow']}/{h['schema']}/{h['qid']}: {h['text']!r}")
    if qa["n_hits"] and not allow_question_overlap:
        raise SystemExit("question/criterion text overlaps an eval question text: reword those schemas "
                         "(or pass --allow-question-overlap to override, and disclose it)")
    flagged = set(st["flagged"])
    kept = [r for r in records if r["id"] not in flagged]
    st = {k: v for k, v in st.items() if k != "flagged"} | {"flagged_ids": sorted(flagged)}
    return kept, {"path": str(path), "states": st, "question_texts": qa}


def build(a):
    names = None if a.workflows in (None, "", "all") else [w.strip() for w in a.workflows.split(",") if w.strip()]
    workflows = sw.load_all(names)
    if a.target_cases:
        n_schemas = sum(len(wf.schemas) for wf in workflows.values())
        a.cases_per_schema = -(-a.target_cases // n_schemas)
        print(f"--target-cases {a.target_cases}: {n_schemas} schemas -> {a.cases_per_schema} cases per schema")
    dev = resolve_dev(set(workflows), a.dev_workflows)
    records, stats = build_records(workflows, a.cases_per_schema, a.seed, dev, a.val_pct)
    bad = [(r["id"], e) for r in records for e in contract.validate_unlabelled(r)]
    if bad:
        raise SystemExit(f"{len(bad)} contract violations, first: {bad[:3]}")
    audit = None
    if a.exclude_states:
        records, audit = run_audits(records, workflows, a.exclude_states, a.allow_question_overlap)
    out = Path(a.out)
    written = write_corpus(out, records)
    summary = summarise(records)
    manifest = {
        "generator": SOURCE_PREFIX, "generator_version": base.GENERATOR_VERSION,
        "args": {"cases_per_schema": a.cases_per_schema, "target_cases": a.target_cases, "seed": a.seed, "workflows": sorted(workflows),
                 "dev_workflows": dev, "val_pct": a.val_pct, "exclude_states": a.exclude_states},
        "contract": "research/typed_synth_spec.md section 5; synth_workflows/contract.py",
        "exclusion_list": {"workflows": sorted(exclusion.EXCLUDED_WORKFLOWS),
                           "n_schemas": len(exclusion.EXCLUDED_SCHEMAS)},
        "schemas": {w: [s.name for s in wf.schemas] for w, wf in sorted(workflows.items())},
        "files": written, "summary": summary, "build_stats": stats, "audit": audit,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({k: summary[k] for k in ("records", "units", "by_split", "qtype_mix", "k_hist",
                                              "noul_definitions", "surface_json_share", "state_chars")}, indent=1))
    print(f"wrote {len(records)} unlabelled records to {out} ({len(written)} files); dev workflows (val): {dev}")
    if stats["short_schemas"]:
        print(f"WARNING: schemas short of {a.cases_per_schema} unique cases: {stats['short_schemas']}")


