# =========================================================================== label audit (after labelling)
def label_audit(path):
    """Per question: mean top-p, entropy, how often the argmax is the SAME answer (collapse), and the mutual
    information between each latent factor and the gold argmax as a fraction of the argmax entropy (the
    Latent Node write-up's audit; its published questions span 0.12-0.85). Reads labelled records only."""
    files = sorted(Path(path).glob("*/*.jsonl")) + sorted(Path(path).glob("*.jsonl"))
    rows = defaultdict(list)
    for p in files:
        for line in p.open(encoding="utf-8"):
            r = json.loads(line)
            if "labels" not in r:
                continue
            for qid, lab in r["labels"].items():
                rows[(r["meta"]["workflow"], r["meta"]["schema"], qid)].append((lab, r["meta"]["factors"]))

    def ent(ps):
        return -sum(p * math.log(p) for p in ps if p > 0)

    def binned(v):
        if isinstance(v, bool) or v is None or isinstance(v, str):
            return str(v)
        if isinstance(v, (int, float)):
            return f"{v:.3g}"
        return json.dumps(v, sort_keys=True)[:40]

    print(f"{'workflow/schema/qid':70s} {'n':>5s} {'top_p':>6s} {'H':>5s} {'mode%':>6s} {'bestMI':>7s}  factor")
    for (w, s, q), items in sorted(rows.items()):
        n = len(items)
        top = sum(max(lab.values()) for lab, _ in items) / n
        h = sum(ent(list(lab.values())) for lab, _ in items) / n
        am = [max(lab, key=lab.get) for lab, _ in items]
        mode = Counter(am).most_common(1)[0][1] / n
        pa = Counter(am)
        h_a = ent([c / n for c in pa.values()])
        best, bestf = 0.0, "-"
        for fname in items[0][1]:
            vals = []
            for _, f in items:
                v = f.get(fname)
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    vals.append(v)
            # numeric factors: quartile bins; others: their value
            if vals and len(set(vals)) > 6:
                qs = sorted(vals)
                cuts = [qs[int(len(qs) * k / 4)] for k in (1, 2, 3)]

                def key(v, cuts=cuts):
                    return "none" if not isinstance(v, (int, float)) else str(sum(v > c for c in cuts))
            else:
                key = binned
                # ids, names, free text: plug-in MI of a near-unique variable is ~H(argmax) by construction
                if len({binned(f.get(fname)) for _, f in items}) > min(12, max(2, n // 5)):
                    continue
            joint = Counter((key(f.get(fname)), a) for (_, f), a in zip(items, am))
            px = Counter(key(f.get(fname)) for _, f in items)
            mi = sum(c / n * math.log((c / n) / ((px[x] / n) * (pa[a] / n))) for (x, a), c in joint.items())
            frac = mi / h_a if h_a > 0 else 0.0
            if frac > best:
                best, bestf = frac, fname
        flag = "  COLLAPSED" if mode > 0.9 else ""
        print(f"{w + '/' + s + '/' + q:70s} {n:5d} {top:6.3f} {h:5.3f} {mode * 100:5.1f}% {best:7.3f}  {bestf}{flag}")
    print("\n(best single-factor MI / argmax entropy; the benchmark's audit reports 0.119-0.850 per question. "
          "mode% > 90 = the question collapses onto one answer.)")


# =========================================================================== self-test
def load_cf():
    """trainers/cache_features.py, stubbing torch / transformers in memory when they are not installed."""
    stubbed = []
    for mod, attrs in (("torch", {"Tensor": type("Tensor", (), {})}), ("transformers", {"AutoTokenizer": None})):
        try:
            __import__(mod)
        except ImportError:
            m = types.ModuleType(mod)
            for k, v in attrs.items():
                setattr(m, k, v)
            sys.modules[mod] = m
            stubbed.append(mod)
    spec = importlib.util.spec_from_file_location("cache_features_selftest", HERE / "trainers" / "cache_features.py")
    cf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cf)
    spec2 = importlib.util.spec_from_file_location("claude_lmscore_selftest", HERE / "trainers" / "claude_lmscore.py")
    ls = importlib.util.module_from_spec(spec2)
    spec2.loader.exec_module(ls)
    return cf, ls, stubbed


class FakeTok:
    """Whitespace 'tokenizer' with offsets and a Qwen-like chat template: enough to drive build_prompt."""

    bos_token, bos_token_id = None, None

    def __call__(self, text, add_special_tokens=False, return_offsets_mapping=False):
        spans = [(m.start(), m.end()) for m in re.finditer(r"\S+", text)]
        out = {"input_ids": list(range(len(spans)))}
        if return_offsets_mapping:
            out["offset_mapping"] = spans
        return out

    def apply_chat_template(self, msgs, tokenize=False, add_generation_prompt=True, enable_thinking=False):
        return "<|im_start|>user\n" + msgs[0]["content"] + "<|im_end|>\n<|im_start|>assistant\n"


def dummy_labels(rec, rng, score_keys):
    labs = {}
    for qid, q in rec["questions"].items():
        keys = contract.label_keys(q, score_keys)
        w = [rng.random() + 0.01 for _ in keys]
        labs[qid] = {k: x / sum(w) for k, x in zip(keys, w)}
    return labs


def self_test(a):
    ok = True

    def check(cond, msg):
        nonlocal ok
        print(("  ok    " if cond else "  FAIL  ") + msg)
        ok = ok and bool(cond)

    names = None if a.workflows in (None, "", "all") else [w.strip() for w in a.workflows.split(",") if w.strip()]
    print("[1] registry, contract and exclusion checks")
    reg = sw.load_all(names, strict=False)
    for e in sw.load_all.errors:
        print("        " + e)
    check(not sw.load_all.errors and reg, f"{len(reg)} workflows load clean: {sorted(reg)}")
    check(len(exclusion.EXCLUDED_WORKFLOWS) == 4 and len(exclusion.EXCLUDED_SCHEMAS) == 20,
          "exclusion list holds the benchmark's 4 workflows and 20 question schemas")
    n_schemas = sum(len(wf.schemas) for wf in reg.values())
    check(all(len(wf.schemas) >= 5 for wf in reg.values()), f"every workflow has >= 5 schemas ({n_schemas} in all)")
    if not reg:
        raise SystemExit("SELF-TEST FAILED: nothing to test")

    print("[2] every schema x surface renders valid cases (make_case validates state + questions)")
    n_cases, errs = 0, []
    for wf in reg.values():
        for s in wf.schemas:
            for surf in s.surfaces:
                for i in range(6):
                    try:
                        base.make_case(s, base.case_rng("selftest", wf.name, s.name + surf, i), surface=surf)
                        n_cases += 1
                    except Exception as ex:  # noqa: BLE001
                        errs.append(f"{wf.name}/{s.name}/{surf}: {type(ex).__name__}: {ex}")
    for e in errs[:10]:
        print("        " + e)
    check(not errs, f"{n_cases} forced-surface cases rendered")

    print("[3] records: contract, unique ids, splits")
    dev = [w for w in DEFAULT_DEV if w in reg] or ([sorted(reg)[-1]] if len(reg) >= 2 else [])
    recs, stats = build_records(reg, a.self_test_cases, 1234, dev, val_pct=0)
    viol = [(r["id"], e) for r in recs for e in contract.validate_unlabelled(r)]
    for v in viol[:5]:
        print("        ", v)
    check(not viol, f"{len(recs)} records satisfy the unlabelled contract")
    check(all("labels" not in r and "label_kind" not in r and r["unlabelled"] is True for r in recs),
          "no labels / label_kind; unlabelled: true")
    check(len({r["id"] for r in recs}) == len(recs), "record ids unique")
    check(len({norm(r["state"]) for r in recs}) == len(recs), "states unique")
    check(all(len(r["questions"]) == 5 for r in recs), "5 questions per case")
    check(all((r["split"] == "val") == (r["meta"]["workflow"] in dev) for r in recs),
          f"dev workflows {dev} entirely in val, all others in train")
    ks_ok = all(base.K_BOUNDS[q["type"]][0] <= len(base.option_keys(q)) <= base.K_BOUNDS[q["type"]][1]
                for r in recs for q in r["questions"].values())
    check(ks_ok, f"K within bounds {base.K_BOUNDS}")

    print("[4] determinism under the seed")
    again, _ = build_records(reg, a.self_test_cases, 1234, dev, val_pct=0)
    check([json.dumps(r, sort_keys=True) for r in recs] == [json.dumps(r, sort_keys=True) for r in again],
          "same seed -> byte-identical records")
    other, _ = build_records(reg, a.self_test_cases, 4321, dev, val_pct=0)
    same = len({r["state"] for r in recs} & {r["state"] for r in other})
    check(same <= 0.02 * len(recs), f"different seed -> different cases ({same} states shared)")

    print("[5] cache_features.question_options / iter_units with dummy labels; claude_lmscore.build_prompt")
    cf, ls, stubbed = load_cf()
    if stubbed:
        print(f"        (stubbed in memory: {stubbed})")
    rng = random.Random(7)
    with tempfile.TemporaryDirectory() as td:
        write_corpus(Path(td, "unlab"), recs)
        files = sorted(p.relative_to(td).as_posix() for p in Path(td, "unlab").rglob("*.jsonl"))
        check(all(re.fullmatch(r"unlab/(train|val)/typed_synth__[a-z0-9_]+\.jsonl", f) for f in files),
              f"flat layout: {len(files)} files under train/ and val/")
        labelled, qo_err = [], []
        for j, r in enumerate(recs):
            mode = "text" if j % 2 == 0 else "index"
            labs = dummy_labels(r, rng, mode)
            for qid, q in r["questions"].items():
                try:
                    keys, texts, vals = cf.question_options(q, labs[qid])
                    assert keys == base.option_keys(q) and len(texts) == len(vals) == len(keys)
                    assert abs(sum(vals) - 1) < 1e-6 and all(str(t).strip() for t in texts)
                except Exception as ex:  # noqa: BLE001
                    qo_err.append(f"{r['id']}/{qid}: {type(ex).__name__}: {ex}")
            lr = contract.attach_labels(r, labs, "soft", {"teacher": "dummy"})
            e = contract.validate_labelled(lr)
            if e:
                qo_err.append(f"{r['id']}: {e}")
            labelled.append(lr)
        for e in qo_err[:5]:
            print("        " + e)
        check(not qo_err, f"question_options accepts every question ({5 * len(recs)} units; score labels keyed by "
                          f"level text and by index)")
        write_corpus(Path(td, "lab"), labelled)
        units = list(cf.iter_units(str(Path(td, "lab")), ["train", "val"], set(), None))
        check(len(units) == 5 * len(recs), f"iter_units loads {len(units)} units from the labelled records unchanged")
        check(all(u["source"].startswith(SOURCE_PREFIX + "/") and u["label_kind"] == "soft" for u in units),
              "units carry source typed_synth/<workflow> and label_kind soft")
        tok, bp_err = FakeTok(), []
        for u in units[:: max(1, len(units) // 400)]:
            k = len(u["option_texts"])
            text = ls.build_prompt(tok, u, list(range(k)), max_len=100000)
            if not (text and u["instructions"] in text and f"A) {u['option_texts'][0]}" in text
                    and f"{ls.LABELS[k - 1]}) {u['option_texts'][-1]}" in text and u["state"][:200] in text):
                bp_err.append(u["record_id"])
            short = ls.build_prompt(tok, u, list(range(k)), max_len=400)
            if short is not None and u["instructions"] not in short:
                bp_err.append(u["record_id"] + " (truncated)")
        check(not bp_err, "build_prompt renders state, question and lettered options (and truncates only the state)")

    print("[6] n-gram audit catches copies")
    with tempfile.TemporaryDirectory() as td:
        ev = Path(td, "eval.jsonl")
        victim = recs[0]
        some_q = next(iter(victim["questions"].values()))
        with ev.open("w") as f:
            f.write(json.dumps({"state": victim["state"], "questions": {"q": some_q}}) + "\n")
            f.write(json.dumps({"state": "An unrelated artefact about lighthouse keeping rotas and fog signals "
                                         "for the winter season on the northern coast."}) + "\n")
        states, qtexts = exclusion.read_eval(ev)
        st = exclusion.audit_states(recs, states)
        vs = (victim["meta"]["workflow"], victim["meta"]["schema"])
        others = [i for i in st["flagged"] if i != victim["id"]]
        foreign = [r["id"] for r in recs if r["id"] in set(others) and (r["meta"]["workflow"], r["meta"]["schema"]) != vs]
        check(victim["id"] in st["flagged"] and not foreign,
              f"state audit flags the copied state and nothing outside its schema "
              f"({st['n_flagged']} flagged, {len(others)} same-schema look-alikes)")
        qa = exclusion.audit_question_texts(reg.values(), qtexts)
        check(qa["n_hits"] >= 1 and all(h["text"] for h in qa["hits"]), "question-text audit flags a copied instruction")
        qa0 = exclusion.audit_question_texts(reg.values(), ["No relation whatsoever to any of our schemas at all."])
        check(qa0["n_hits"] == 0, "question-text audit is quiet on unrelated text")

    print("[7] summary")
    summ = summarise(recs)
    print(json.dumps({k: summ[k] for k in ("records", "units", "qtype_mix", "k_hist", "noul_definitions",
                                           "surface_json_share", "state_chars")}, indent=1))
    mix = summ["qtype_mix"]
    check(0.3 <= mix["score"] <= 0.5 and 0.2 <= mix["choice"] <= 0.4 and 0.2 <= mix["noul"] <= 0.4,
          f"type mix near the benchmark's 0.40 / 0.30 / 0.30 (score / choice / noul): {mix}")
    check(summ["surface_json_share"] >= 0.3, f"compact-JSON share {summ['surface_json_share']} >= 0.3")
    print("\nSELF-TEST " + ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


