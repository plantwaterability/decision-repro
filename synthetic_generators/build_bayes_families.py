# ============================================================================ CLI
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--out", required=True)
    b.add_argument("--scale", type=float, default=1.0)
    b.add_argument("--forbid-numeric", default=None, help="numeric_v2 root (val / test texts and coin / rate fingerprints)")
    b.add_argument("--forbid-bc", default=None, help="BC suite v2 root")
    b.add_argument("--splits", default=",".join(SPLITS))
    b.add_argument("--salt-file", default=None, help="(confirm builds) a private salt file; never printed or recorded")
    b.add_argument("--exclude-built", default=None, help="(confirm builds) the public build whose texts / fingerprints are refused")
    c = sub.add_parser("check")
    c.add_argument("root")
    c.add_argument("--forbid-numeric", default=None)
    c.add_argument("--forbid-bc", default=None)
    c.add_argument("--mp-sample", type=int, default=150)
    c.add_argument("--json", default="")
    sub.add_parser("self-test")
    a = ap.parse_args(argv)
    if a.cmd == "build":
        salt = None
        if a.salt_file:
            salt = Path(a.salt_file).read_text().strip()
        man = build(a.out, a.scale, numeric_dir=a.forbid_numeric, bc_dir=a.forbid_bc, splits=tuple(a.splits.split(",")), salt=salt,
                    exclude_built=a.exclude_built)
        print(json.dumps({k: man[k] for k in ("counts", "numerics", "build_secs")}, indent=1))
        return 0
    if a.cmd == "check":
        rep = check(a.root, a.forbid_numeric, a.forbid_bc, a.mp_sample)
        s = json.dumps(rep, indent=1, default=str)
        print(s)
        if a.json:
            Path(a.json).write_text(s)
        return 0 if rep["n_errors"] == 0 else 1
    if a.cmd == "self-test":
        res = self_test()
        print(json.dumps(res, indent=1))
        return 0 if all(v.get("ok", True) for v in res.values()) else 1
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
