def event_round(t, sd, unit_interval=False, positive=True):
    """A decision threshold near t, rounded to a step of 10^floor(log10(sd / 2)) (0.05 / 0.01 grid inside [0.05, 0.95] for
    probabilities). Exact; reads only visible-evidence quantities."""
    t, sd = D(t), D(sd)
    if unit_interval:
        step = Decimal("0.05") if sd >= Decimal("0.05") else Decimal("0.01")
        v = DC.multiply(DC.divide(t, step).to_integral_value(rounding=ROUND_HALF_EVEN), step)
        return min(max(Q(v), Fraction(1, 20)), Fraction(19, 20))
    step = pow10_floor(DC.divide(sd, Decimal(2)))
    v = Q(DC.multiply(DC.divide(t, step).to_integral_value(rounding=ROUND_HALF_EVEN), step))
    if positive and v <= 0:
        v = Q(step)
    return v


