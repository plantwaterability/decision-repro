class CatGen(Gen):
    name, sym, heldout_gen = "categorical", "q", True

    def contexts(self, heldout):
        return CAT_CTX

    def render(self, Rr, ctx):
        return {"i_prior": Rr.randrange(2), "i_q": Rr.randrange(2), "pct": Rr.random() < 0.25, "j": Rr.randrange(len(ctx["cats"])),
                "i_restate": Rr.randrange(2)}

    def draw_prior(self, Rw, reg, ctx=None):
        kc = len(ctx["cats"])
        u = Rw.random()
        if u < 0.25:
            return {"alpha": [Fraction(1)] * kc}
        if u < 0.35:
            return {"alpha": [Fraction(1, 2)] * kc}
        return {"alpha": [Fraction(1 + Rw.randrange(12)) for _ in range(kc)]}

    def prior_dist(self, pr, j=None):
        a = pr["alpha"]
        return Beta(a[j], sum(a) - a[j])

    def prior_line(self, pr, ctx, ri):
        parts = ", ".join(f"{c} {pnum(a)}" for c, a in zip(ctx["cats"], pr["alpha"]))
        return [f"Prior: the probabilities follow a Dirichlet distribution with parameters {parts}.",
                f"Before any data, your belief about the probabilities is Dirichlet({parts})."][ri["i_prior"]]

    def draw_truth(self, Rw, pr, broad):
        gs = []
        for a in pr["alpha"]:
            gs.append(Q(rsig(-dln(unif(Rw) or Decimal("1e-300")), 6)) if broad else draw_quantile(Gamma(a, 1), Rw))
        tot = sum(gs, Fraction(0))
        return [g / tot for g in gs]

    def draw_block(self, Rw, truth, n, **kw):
        cum, acc = [], Fraction(0)
        for p in truth:
            acc += p
            cum.append(fl(acc))
        cnt = [0] * len(truth)
        for _ in range(n):
            u = Rw.random()
            j = next((i for i, c in enumerate(cum) if u < c), len(cum) - 1)
            cnt[j] += 1
        return {"counts": cnt, "n": n}

    def stats(self, blocks):
        kc = len(blocks[0]["counts"]) if blocks else 0
        return {"n": sum(b["n"] for b in blocks), "counts": [sum(b["counts"][i] for b in blocks) for i in range(kc)]}

    def posterior(self, pr, blocks, j=None):
        s = self.stats(blocks)
        a = list(pr["alpha"])
        if blocks:
            a = [x + c for x, c in zip(a, s["counts"])]
        return Beta(a[j], sum(a) - a[j])

    def data_only(self, blocks, j=None):
        s = self.stats(blocks)
        if not blocks or s["n"] == 0:
            return None
        kc = len(s["counts"])
        return Beta(s["counts"][j] + 1, s["n"] - s["counts"][j] + kc - 1)

    def scale_block(self, b, k):
        return {"counts": [c * k for c in b["counts"]], "n": b["n"] * k}

    def _cnt(self, b, ctx):
        parts = [f"{c} {name}" for c, name in zip(b["counts"], ctx["cats"])]
        return ", ".join(parts[:-1]) + " and " + parts[-1]

    def data_line(self, b, ctx, ri, alt=False, pr=None):
        if b["n"] == 0:
            return f"No {ctx['trial'][1]} have been observed yet."
        if alt:
            return f"To repeat (the same {ctx['trial'][1]} as above, not new ones): {self._cnt(b, ctx)}."
        return f"Results of {b['n']} {pl(b['n'], ctx['trial'])}: {self._cnt(b, ctx)}."

    def batch_line(self, i, b, ctx, pr=None):
        return f"Batch {i}: {b['n']} {pl(b['n'], ctx['trial'])}: {self._cnt(b, ctx)}."

    def restate_line(self, b, ctx, ri, pr=None):
        return self.data_line(b, ctx, ri, alt=True)

    def other_unit_line(self, b2, ctx, pr=None):
        return f"Separately, and unrelated to q: {ctx['other']} gave {self._cnt(b2, ctx)} in {b2['n']} {pl(b2['n'], ctx['trial'])}."

    def axis(self, blocks, ctx, ri, Ra, pr=None):
        ax, disp, nat = natural_axis(ri["pct"])
        return ax, disp, nat, ("percentage points" if ri["pct"] else "")

    def question(self, ctx, ri, ax, disp):
        c = ctx["cats"][ri["j"]]
        sym = "q (in percent)" if ri["pct"] else "q"
        lead = [f"Let q be {ctx['what'].format(c=c)}. Which bin contains {sym}?",
                f"Let q be {ctx['what'].format(c=c)}. In which interval does {sym} lie?"][ri["i_q"]]
        return lead + " " + axis_text(ax, disp, "percentage points" if ri["pct"] else "")

    def event(self, Rw, blocks, ctx, pr=None, j=None):
        s = self.stats(blocks)
        kc = len(s["counts"])
        d = Beta(s["counts"][j] + 1, s["n"] - s["counts"][j] + kc - 1)
        t = event_round(DC.add(D(d.mean), DC.multiply(uni(Rw, -1, 1), dsqrt(d.var))), dsqrt(d.var), unit_interval=True)
        c = ctx["cats"][j]
        what = ctx["what"].format(c=c)
        return t, f"{what} is above {txt(t)}", f"Is {what} above {txt(t)}?"

    def anchor(self, Rw, blocks, pr=None):
        x = 5 + Rw.randrange(91)
        return ANCHOR_LINE.format(x=x), Fraction(x, 100)

    def numeric_fp(self, pr, blocks):
        return None

    def n_base(self, Rw, reg):
        return rint(logu(Rw, 3, 120))

    def prior_swaps(self, Rw, reg, ctx=None, j=0):
        kc = len(ctx["cats"])
        base = [Fraction(1 + Rw.randrange(8)) for _ in range(kc)]
        k = 3 + Rw.randrange(2)
        weak, strong = base, [a * k for a in base]
        b, S = (strong, weak) if Rw.random() < 0.5 else (weak, strong)
        o = max((i for i in range(kc) if i != j), key=lambda i: (b[i], -i))
        d = max(1, rint(DC.multiply(uni(Rw, "0.3", "0.7"), D(b[o]))))
        if Rw.random() < 0.5:
            d = -min(d, int(b[j]) - 1) if b[j] > 1 else d
        M = list(b)
        M[j], M[o] = b[j] + d, b[o] - d
        if M[o] < 1 or M[j] < 1 or M == b or all(a == 1 for a in b):
            return None
        P = lambda t: {"alpha": list(t)}
        return {"base": (P(b), {"kind": "base"}), "strength": (P(S), {"kind": "strength", "k": str(S[0] / b[0])}),
                "mean": (P(M), {"kind": "mean", "shift": int(d)}), "flat": (P([Fraction(1)] * kc), {"kind": "uniform"})}


class LRGen(Gen):
    name, kind, sym = "lr", "binary", "H"

    def contexts(self, heldout):
        return LR_HELDOUT if heldout else LR_CTX

    def render(self, Rr, ctx):
        return {"i_prior": Rr.randrange(2), "test0": Rr.randrange(3)}

    def draw_prior(self, Rw, reg):
        if reg == "heldout":
            return {"p": Fraction(10 + Rw.randrange(191), 10000)}         # 0.10% .. 2.00% (0.01-point grid)
        return {"p": Fraction(50 + Rw.randrange(901), 1000)}               # 5.0% .. 95.0% (one decimal: enough distinct prior-only texts)

    def draw_test(self, Rw, reg):
        if reg == "heldout":
            return {"sens": Fraction(900 + Rw.randrange(100), 1000), "spec": Fraction(970 + Rw.randrange(30), 1000)}
        return {"sens": Fraction(60 + Rw.randrange(36), 100), "spec": Fraction(60 + Rw.randrange(36), 100)}

    def pct(self, p):
        return txt(p * 100)

    def prior_line(self, pr, ctx, ri):
        return ctx["prior"][ri["i_prior"]].format(p=self.pct(pr["p"]))

    def draw_truth(self, Rw, pr, broad):
        return int(Rw.random() < fl(Fraction(1, 2) if broad else pr["p"]))

    def result(self, Rw, test, H):
        return int(Rw.random() < fl(test["sens"] if H else 1 - test["spec"]))

    @staticmethod
    def lr_of(b):
        sens, spec = b["sens"], b["spec"]
        one = sens / (1 - spec) if b["res"] else (1 - sens) / spec
        return one ** b.get("k", 1)

    def posterior(self, pr, blocks):
        o = pr["p"] / (1 - pr["p"])
        for b in blocks:
            o *= self.lr_of(b)
        return Bern(o / (1 + o))

    def data_only(self, blocks):
        return self.posterior({"p": Fraction(1, 2)}, blocks)

    def prior_dist(self, pr):
        return Bern(pr["p"])

    def stats(self, blocks):
        return {"tests": len(blocks), "checks": [[exact_str(b["sens"]), exact_str(b["spec"]), int(b["res"]), int(b.get("k", 1))]
                                                 for b in blocks]}

    def test_desc(self, b, ctx):
        name = ctx["tests"][b["test"]]
        return (f"The {name} gives {ctx['pos'][0]} {self.pct(b['sens'])}% of the time when {ctx['H']}, and "
                f"{self.pct(1 - b['spec'])}% of the time otherwise.")

    def res_txt(self, b, ctx):
        return ctx["pos"][1] if b["res"] else ctx["neg"]

    def data_line(self, b, ctx, ri, alt=False):
        k = b.get("k", 1)
        if k == 1:
            return f"{self.test_desc(b, ctx)} It was run once. Result: {self.res_txt(b, ctx)}."
        times = {2: "twice", 3: "three times", 4: "four times"}[k]
        alln = {2: "Both results", 3: "All three results", 4: "All four results"}[k]
        return (f"{self.test_desc(b, ctx)} It was run {times}; given whether {ctx['H']}, the runs are independent. "
                f"{alln}: {self.res_txt(b, ctx)}.")

    def batch_line(self, i, b, ctx):
        return f"Check {i}: {self.test_desc(b, ctx)} Result: {self.res_txt(b, ctx)}."

    def indep_line(self, ctx):
        return f"Given whether {ctx['H']}, the checks below are independent of each other."

    def restate_line(self, b, ctx, ri):
        return f"To repeat (the same result as above, not a new run): the {ctx['tests'][b['test']]} gave {self.res_txt(b, ctx)}."

    def other_unit_line(self, b2, ctx):
        return f"Separately, {ctx['other']} also got the result {self.res_txt(b2, ctx)} from the same {ctx['tests'][b2['test']]}."

    def regime_of(self, pr, blocks):
        return "heldout" if pr["p"] < Fraction(3, 100) else "train"

    def prior_swaps(self, Rw, reg, base_p):
        k = Fraction(3 + Rw.randrange(3))
        o = base_p / (1 - base_p)
        dp = 3 if reg == "heldout" else 1
        up = round_exact((o * k) / (1 + o * k) * 100, dp) / 100
        dn = round_exact((o / k) / (1 + o / k) * 100, dp) / 100
        if up in (base_p, 0, 1) or dn in (base_p, 0, 1) or base_p == Fraction(1, 2) or up == dn:
            return None
        if reg != "heldout" and not (Fraction(5, 100) <= dn and up <= Fraction(95, 100)):
            return None
        if reg == "heldout" and dn <= 0:
            return None
        P = lambda p: {"p": p}
        return {"base": (P(base_p), {"kind": "base"}), "odds_up": (P(up), {"kind": "odds_up", "k": str(k)}),
                "odds_down": (P(dn), {"kind": "odds_down", "k": str(k)}), "flat": (P(Fraction(1, 2)), {"kind": "fifty"})}


