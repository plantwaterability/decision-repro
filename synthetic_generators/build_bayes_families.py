STRATA = ((Fraction(5, 100), Fraction(35, 100)), (Fraction(35, 100), Fraction(65, 100)), (Fraction(65, 100), Fraction(95, 100)))


def _u_fr(R, lo, hi):
    return lo + Fraction(R.random()) * (hi - lo)


def matrix2(R, stratum, unit):
    """Two options: R = (C if event, 0 if not), S = (s_e, s_n). Indifference p* = s_n / (C - s_e + s_n), drawn in the stratum."""
    for _ in range(200):
        C = 20 + R.randrange(81)
        s_e = int(C * Fraction(R.randrange(51), 100))
        p = _u_fr(R, *stratum)
        s_n = int(round(p * (C - s_e) / (1 - p)))
        if s_n < 1:
            continue
        ps = Fraction(s_n, C - s_e + s_n)
        if stratum[0] <= ps <= stratum[1]:
            return {"R": (C * unit, 0), "S": (s_e * unit, s_n * unit)}
    raise Dup("matrix2")


def matrix3(R, stratum, unit):
    """Three options: R = (C, 0), S = (s, s), H = (h_e, h_n) optimal on a middle band; band centre in the stratum."""
    for _ in range(400):
        C = 20 + R.randrange(81)
        s = int(round(C * _u_fr(R, Fraction(10, 100), Fraction(90, 100))))
        if not 1 <= s < C:
            continue
        pAB = Fraction(s, C)
        dl = _u_fr(R, Fraction(15, 100), Fraction(40, 100))
        h_e = int(round(C * _u_fr(R, Fraction(40, 100), Fraction(90, 100))))
        h_n = int(round(((1 - dl) * s - pAB * h_e) / (1 - pAB)))
        if not (0 <= h_n < s and s < h_e < C):
            continue
        p1 = Fraction(h_n, C - h_e + h_n)
        p2 = Fraction(s - h_n, h_e - h_n)
        if not (0 < p1 < p2 < 1):
            continue
        if stratum[0] <= (p1 + p2) / 2 <= stratum[1]:
            return {"R": (C * unit, 0), "S": (s * unit, s * unit), "H": (h_e * unit, h_n * unit)}
    raise Dup("matrix3")


def thresholds(costs):
    """Exact indifference points between every pair of options (where they cross inside (0, 1))."""
    out = {}
    names = list(costs)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            (ae, an), (be, bn_) = costs[names[i]], costs[names[j]]
            den = (ae - an) - (be - bn_)
            if den != 0:
                p = Fraction(bn_ - an, den)
                if 0 < p < 1:
                    out[f"{names[i]}|{names[j]}"] = exact_str(p)
    return out


def decide(costs_by_key, p):
    ec = {k: p * ce + (1 - p) * cn for k, (ce, cn) in costs_by_key.items()}
    best = min(ec.values())
    winners = [k for k, v in ec.items() if v == best]
    return ec, winners


def fam_loss(B, G):
    g = G.gen
    pr = base_problem(G)
    if g.name == "lr":
        test = {**g.draw_test(G.Rw, G.reg), "test": G.ri["test0"], "k": 1}
        test["res"] = g.result(G.Rw, test, G.truth)
        blocks = [test]
        data_lines = [g.data_line(test, G.ctx, G.ri)]
        post, prd, dod = posterior_of(G, pr, blocks), prior_of(G, pr), data_only_of(G, blocks)
        pe = round_exact(post.p, EVENT_DP)
        pe_prior, pe_data = round_exact(prd.p, EVENT_DP), round_exact(dod.p, EVENT_DP)
        ev_text, belief_q, event = G.ctx["H"], G.ctx["q"], None
        intro = G.ctx["intro"]
    else:
        n = size_for(G)
        if g.name == "coin":
            n = max(3, n)
        b = draw_data(G, pr, n)
        data_ok(G, b)
        blocks = [b]
        check_regime(G, pr, blocks)
        if g.name == "categorical":
            t, ev_text, belief_q = g.event(G.Rl, blocks, G.ctx, pr=pr, j=G.ri["j"])
        else:
            t, ev_text, belief_q = _gen_call(g, "event", G.Rl, blocks, G.ctx, pr=pr)
        event = {"t": t, "text": ev_text, "question": belief_q}
        post, prd, dod = posterior_of(G, pr, blocks), prior_of(G, pr), data_only_of(G, blocks)
        pe = p_above(post, t, EVENT_DP)
        pe_prior = p_above(prd, t, EVENT_DP)
        pe_data = p_above(dod, t, EVENT_DP) if dod is not None else pe_prior
        data_lines = [dline(G, b, pr)]
        intro = intro_line(G, pr)
    head = [intro, g.prior_line(pr, G.ctx, G.ri)] + data_lines
    R = G.Rl
    three = R.random() < 0.3
    unit = (1, 10, 100, 1000)[R.randrange(4)]
    strata = list(STRATA)
    R.shuffle(strata)
    mats = [(matrix3 if three else matrix2)(R, s, unit) for s in strata]
    roles = ["R", "S", "H"] if three else ["R", "S"]
    R.shuffle(roles)                                  # which option number is which role: fixed for the whole group
    keys = [f"a{i}" for i in range(len(roles))]
    mscale = (2, 3, 5, 10)[R.randrange(4)]
    shift_state = "e" if R.random() < 0.5 else "n"
    maxc = max(max(v) for v in mats[1].values())
    shift = int(maxc * Fraction(20 + R.randrange(81), 100)) or unit
    L1s = {r: (c[0] * mscale, c[1] * mscale) for r, c in mats[0].items()}
    L2t = {r: ((c[0] + shift, c[1]) if shift_state == "e" else (c[0], c[1] + shift)) for r, c in mats[1].items()}
    members = [("L1", mats[0], {"kind": "matrix", "stratum": [exact_str(x) for x in strata[0]]}),
               ("L2", mats[1], {"kind": "matrix", "stratum": [exact_str(x) for x in strata[1]]}),
               ("L3", mats[2], {"kind": "matrix", "stratum": [exact_str(x) for x in strata[2]]}),
               ("L1s", L1s, {"kind": "scaled", "of": "L1", "factor": mscale}),
               ("L2t", L2t, {"kind": "shifted", "of": "L2", "add": shift, "state": "event" if shift_state == "e" else "not_event"})]
    make_record(B, G, "noloss", "belief", head, pr, blocks, {"kind": "noloss"}, event=event, anchor=True)
    for name, mat, fac in members:
        costs = {k: mat[r] for k, r in zip(keys, roles)}
        lines = [LOSS_HEAD.format(m=len(keys), ev=ev_text)] + [
            LOSS_ROW.format(i=i + 1, ce=money(costs[k][0]), cn=money(costs[k][1]), ev=ev_text) for i, k in enumerate(keys)]
        ec, win = decide(costs, pe)
        _, win_p = decide(costs, pe_prior)
        _, win_d = decide(costs, pe_data)
        srt = sorted(ec.values())
        maxe = max(max(c) for c in costs.values())
        dec = {"event": ev_text, "t": exact_str(event["t"]) if event else None, "p_event": float(pe), "p_event_exact10": exact_str(pe), "p_event_prior": float(pe_prior),
               "p_event_data_only": float(pe_data),
               "plans": [{"key": k, "label": f"Option {i + 1}", "role": r, "cost_if_event": costs[k][0], "cost_if_not": costs[k][1]}
                         for i, (k, r) in enumerate(zip(keys, roles))],
               "expected_cost": {k: float(rsig(D(v), 12)) for k, v in ec.items()},
               "bayes_action": win[0] if len(win) == 1 else win, "tie": len(win) > 1,
               "margin": float(rsig(D((srt[1] - srt[0]) / maxe), 8)) if maxe else 0.0,
               "thresholds": thresholds(costs), "max_cost": maxe,
               "prior_action": win_p[0], "data_only_action": win_d[0],
               "target": {k: (Fraction(1, len(win)) if k in win else Fraction(0)) for k in keys}}
        fac = {**fac, "loss": {k: [costs[k][0], costs[k][1]] for k in keys}}
        st = head + lines
        make_record(B, G, name, "belief", st, pr, blocks, fac, event=event)
        make_record(B, G, name, "action", st, pr, blocks, fac, decision=dec)


