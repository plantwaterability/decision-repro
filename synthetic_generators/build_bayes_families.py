# ============================================================================ group context (one underlying problem)
class Group:
    def __init__(self, ns, split, family, gen, gi, attempt):
        self.ns, self.split, self.family, self.gen, self.gi, self.attempt = ns, split, family, GENS[gen], gi, attempt
        key = f"{split}|{family}|{gen}|{gi}|{attempt}"
        self.Rw = random.Random(seed_int(ns, key, "world"))
        self.Rr = random.Random(seed_int(ns, key, "render"))
        self.Ra_key = (ns, key, "axis")
        self.Rd = random.Random(seed_int(ns, key, "distract"))
        self.Rl = random.Random(seed_int(ns, key, "loss"))
        self.gid = f"{split}/{family}/{gen}/{gi:05d}"
        self.reg = "heldout" if slice_of(split) == "reg" else "train"
        self.dom = slice_of(split) == "dom"
        ctxs = self.gen.contexts(self.dom)
        self.ctx = ctxs[self.Rr.randrange(len(ctxs))]
        self.ri = self.gen.render(self.Rr, self.ctx)
        self.broad = self.Rw.random() < fl(P_BROAD)
        self.members = []

    def Ra(self, tag="shared"):
        return random.Random(seed_int(*self.Ra_key, tag))


