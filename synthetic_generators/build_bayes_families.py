        m = Fraction(rint(DC.multiply(uni(Rw, "0.1", "0.9"), Decimal(20))), 20)
        s0 = Q(logu(Rw, 2, 40))
        a, b = max(1, round(m * s0)), max(1, round((1 - m) * s0))
        k = 3 + Rw.randrange(2)
        weak, strong = (a, b), (k * a, k * b)
        base, S = (strong, weak) if Rw.random() < 0.5 else (weak, strong)
        tb = base[0] + base[1]
        d = (1 if Rw.random() < 0.5 else -1) * max(1, rint(DC.multiply(uni(Rw, "0.15", "0.35"), Decimal(tb))))
