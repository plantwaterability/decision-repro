def load_forbidden(numeric_dir=None, bc_dir=None):
    """Question texts and coin / rate problem fingerprints of numeric_v2 val / test and the BC suite v2: train must avoid them."""
    texts, nfps, n = set(), set(), Counter()
    for root, splits in ((numeric_dir, ("val", "test")), (bc_dir, ("test",))):
        if not root:
            continue
        for s in splits:
            for p in sorted((Path(root) / s).glob("*.jsonl")):
                for ln in open(p, encoding="utf-8"):
                    r = json.loads(ln)
                    (qid, q), = r["questions"].items()
                    texts.add(r["state"] + "\n" + q["instructions"])
                    m = r["meta"]
                    fp = m.get("fingerprint", "")
                    if fp.startswith(("coin|", "rate|")):
                        nfps.add(fp)
                    if "bc" in m:
                        try:
                            bfp = _bc_numeric_fp(m)
                            if bfp:
                                nfps.add(bfp)
                        except Exception:
                            pass
                    n[f"{Path(root).name}/{s}"] += 1
    return texts, nfps, dict(n)


def _bc_numeric_fp(m):
    bc = m["bc"]
    pr = bc["problem"]["prior"]
    blocks = bc["problem"]["blocks"]
    if pr.get("dist") == "beta":
        n = h = 0
        for b in blocks:
            if b["kind"] == "seq":
                n += len(b["x"])
                h += sum(b["x"])
            else:
                n += int(b["n"])
                h += int(b["h"])
        return f"coin|{fparam(Q(pr['a']))}|{fparam(Q(pr['b']))}|{n}|{h}"
    if pr.get("dist") == "gamma":
        tot, T = 0, Fraction(0)
        for b in blocks:
            if b["kind"] == "list":
                tot += sum(int(c) for c in b["counts"])
                T += len(b["counts"]) * Q(b["L"])
            else:
                tot += int(b["tot"])
                T += Q(b["T"])
        return f"rate|{pr['shape']}|{fsig(Q(pr['rate']), 3)}|{tot}|{fsig(T, 6)}"
    return None


