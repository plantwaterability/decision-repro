def build_group(B, split, family, gen, gi, max_attempts=200):
    last = None
    for att in range(max_attempts):
        G = Group(B.ns, split, family, gen, gi, att)
        try:
            FAM_FN[family](B, G)
        except Dup as e:
            last = e
            STATS[f"redraw/{family}/{gen}"] += 1
            continue
        fps = {r["meta"]["fingerprint"] for r in G.members}
        nfps = {r["meta"]["bf"].get("numeric_fp") for r in G.members} - {None}
        if split == "train" and (fps & B.eval_fp or nfps & B.forbid_nfp):
            STATS[f"redraw_overlap/{family}/{gen}"] += 1
            continue
        if split == "train" and any(r["meta"]["bf"]["regime"] != "train" for r in G.members):
            STATS[f"redraw_regime/{family}/{gen}"] += 1
            continue
        if split in CONFIRM_SPLITS and fps & B.public_fp:
            STATS[f"redraw_public/{family}/{gen}"] += 1
            continue
        for r in G.members:
            B.seen.add(r["state"] + "\n" + next(iter(r["questions"].values()))["instructions"])
            if split != "train":
                B.eval_fp.add(r["meta"]["fingerprint"])
        return G
    raise RuntimeError(f"cannot build {split}/{family}/{gen}/{gi}: {last}")


