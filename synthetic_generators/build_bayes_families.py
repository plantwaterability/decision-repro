        u = Rw.random()
        if u < 0.2:
            return {"a": Fraction(1), "b": Fraction(1)}
        if u < 0.26:
            return {"a": Fraction(1, 2), "b": Fraction(1, 2)}
        m = Fraction(1 + Rw.randrange(19), 20)
        s = Q(logu(Rw, 2, 60))
